"""
What:     Keeps uploads and results as plain files under DATA_DIR: uploads/{id}.pdf and results/{id}.json.
In:       Job ids (32 lowercase hex characters, generated by the API), PDF bytes, ExtractionResult objects.
Out:      The same objects read back, or None for an id that doesn't exist.
Fails if: Two server processes write the same job at once. Writes are atomic (temp file + rename) but there's
          no locking, which is fine for the single-process deployment this project targets.

The id format is checked before it touches the filesystem, so a request for '../../etc/passwd' can't escape DATA_DIR.
"""

import os
import re
import tempfile
from pathlib import Path

from app.models import ExtractionResult, JobStatus

_JOB_ID = re.compile(r"^[0-9a-f]{32}$")


class InvalidJobId(ValueError):
    """Not a job id this server could have issued."""


class Storage:
    def __init__(self, root: Path | str):
        self.root = Path(root)
        for folder in ("uploads", "results"):
            (self.root / folder).mkdir(parents=True, exist_ok=True)

    @classmethod
    def from_env(cls) -> "Storage":
        return cls(os.environ.get("DATA_DIR") or "./data")

    def save_upload(self, job_id: str, data: bytes) -> None:
        _atomic_write(self._path("uploads", job_id, ".pdf"), data)

    def load_upload(self, job_id: str) -> bytes:
        return self._path("uploads", job_id, ".pdf").read_bytes()

    def save_result(self, result: ExtractionResult) -> None:
        _atomic_write(self._path("results", result.id, ".json"), result.model_dump_json(indent=2).encode())

    def load_result(self, job_id: str) -> ExtractionResult | None:
        path = self._path("results", job_id, ".json")
        if not path.is_file():
            return None
        return ExtractionResult.model_validate_json(path.read_bytes())

    def fail_interrupted(self, message: str) -> list[str]:
        """Mark every still-pending job as failed. Called at startup: background jobs don't survive a restart."""
        failed = []
        for path in sorted((self.root / "results").glob("*.json")):
            result = ExtractionResult.model_validate_json(path.read_bytes())
            if result.status is JobStatus.PENDING:
                self.save_result(ExtractionResult(**(dict(result) | {"status": JobStatus.FAILED, "error": message})))
                failed.append(result.id)
        return failed

    def _path(self, folder: str, job_id: str, suffix: str) -> Path:
        if not _JOB_ID.match(job_id):
            raise InvalidJobId(job_id)
        return self.root / folder / f"{job_id}{suffix}"


def _atomic_write(path: Path, data: bytes) -> None:
    """Readers see the old file or the new one, never half of one."""
    fd, tmp = tempfile.mkstemp(dir=path.parent, prefix=f".{path.name}.", suffix=".tmp")
    try:
        with os.fdopen(fd, "wb") as f:
            f.write(data)
        os.replace(tmp, path)
    except BaseException:
        Path(tmp).unlink(missing_ok=True)
        raise
